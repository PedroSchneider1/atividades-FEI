package Pessoas;

/**
 *
 * @author unifpschneider
 */
public class Pessoa {
    protected String nome, sobrenome;
    protected int idade;

    public Pessoa() {
    }
    
    public Pessoa(String nome, String sobrenome, int idade) {
        this.nome = nome;
        this.sobrenome = sobrenome;
        this.idade = idade;
    }

    public String getNome() {
        return nome;
    }

    public String getSobrenome() {
        return sobrenome;
    }

    public int getIdade() {
        return idade;
    }
}
